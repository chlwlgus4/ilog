-- Account and family deletion lifecycle.
-- Individual caregivers can leave a shared family while shared content remains.
-- A family owner can schedule a whole-family purge, with a 30 day cancellation window.

alter table public.families
    add column if not exists owner_caregiver_id bigint,
    add column if not exists deletion_requested_at timestamptz,
    add column if not exists deletion_scheduled_for timestamptz,
    add column if not exists deletion_requested_by_auth_user_id uuid;

update public.families family
set owner_caregiver_id = (
    select caregiver.id
    from public.caregivers caregiver
    where caregiver.family_id = family.id
    order by caregiver.id asc
    limit 1
)
where family.owner_caregiver_id is null;

alter table public.families
    drop constraint if exists families_owner_caregiver_id_fkey;

alter table public.families
